#!/usr/bin/env node
// Generates the color token files for both platforms from tokens/colors.json (the Figma `02 Semantics`
// export), so web and iOS cannot drift apart.
//
//   node tokens/generate.mjs          write web/src/styles/colors.css and DSColor+Tokens.swift
//   node tokens/generate.mjs --check  exit 1 if either file is out of date (for CI)

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const { modes, colors } = JSON.parse(readFileSync(join(root, 'tokens/colors.json'), 'utf8'))

// Figma mode -> CSS data-theme, color-scheme, Swift DSColor argument label.
const modeInfo = {
  Light: { theme: 'light', scheme: 'light', swift: 'light' },
  Dark: { theme: 'dark', scheme: 'dark', swift: 'dark' },
  'EVA Light': { theme: 'eva-light', scheme: 'light', swift: 'evaLight' },
  'EVA Dark': { theme: 'eva-dark', scheme: 'dark', swift: 'evaDark' },
  'Heritage Luxury Light': { theme: 'heritage-luxury-light', scheme: 'light', swift: 'heritageLuxuryLight' },
  'Heritage Luxury Dark': { theme: 'heritage-luxury-dark', scheme: 'dark', swift: 'heritageLuxuryDark' },
}
for (const mode of modes) if (!modeInfo[mode]) throw new Error(`Unknown mode "${mode}": add it to modeInfo`)

const names = Object.keys(colors)
const header = 'Generated by tokens/generate.mjs from tokens/colors.json (Figma Tokens file 5iR1wP3qoTT4uD6d20ekVv,\ncollection "02 Semantics"). Do not edit: change the colors in Figma, export, then run `node tokens/generate.mjs`.'

// `color/background/brand/primary-pressed` -> `--color-background-brand-primary-pressed`
const cssName = (name) => `--${name.replaceAll('/', '-')}`
// `color/background/brand/primary-pressed` -> `backgroundBrandPrimaryPressed`
const swiftName = (name) =>
  name
    .replace(/^color\//, '')
    .split(/[/-]/)
    .map((part, i) => (i === 0 ? part : part[0].toUpperCase() + part.slice(1)))
    .join('')

function css() {
  const blocks = modes.map((mode) => {
    const { theme, scheme } = modeInfo[mode]
    const selector = mode === 'Light' ? `:root,\n[data-theme='${theme}']` : `[data-theme='${theme}']`
    const lines = names.map((name) => `  ${cssName(name)}: #${colors[name][mode].toLowerCase()};`)
    return `${selector} {\n  color-scheme: ${scheme};\n${lines.join('\n')}\n}`
  })
  const comment = header.split('\n').map((l) => ` * ${l}`).join('\n')
  return `/*\n${comment}\n *\n * Theme: <html data-theme="${modes.map((m) => modeInfo[m].theme).join('|')}"> (default: light)\n */\n${blocks.join('\n\n')}\n`
}

function swift() {
  const entries = names.map((name) => {
    const args = modes.map((mode) => `${modeInfo[mode].swift}: "${colors[name][mode]}"`).join(', ')
    return `    /// \`${name}\`\n    static let ${swiftName(name)} = DSColor("${name}", ${args})`
  })
  const all = names.map((name) => `        ${swiftName(name)},`)
  return [
    ...header.split('\n').map((l) => `// ${l}`),
    `// Values per mode: ${modes.join(', ')}. Hex is RRGGBB or RRGGBBAA.`,
    '',
    'public nonisolated extension DSColor {',
    entries.join('\n'),
    '}',
    '',
    'public nonisolated extension DSColor {',
    '    /// Every semantic color, in Figma order, for the Foundations gallery.',
    '    static let all: [DSColor] = [',
    all.join('\n'),
    '    ]',
    '}',
    '',
  ].join('\n')
}

const outputs = [
  ['web/src/styles/colors.css', css()],
  ['ios/YuanhhouDSKit/Sources/YuanhhouDSKit/Tokens/DSColor+Tokens.swift', swift()],
]

const check = process.argv.includes('--check')
let stale = false
for (const [path, content] of outputs) {
  const file = join(root, path)
  let current = ''
  try {
    current = readFileSync(file, 'utf8')
  } catch {
    // Missing file counts as out of date.
  }
  if (current === content) continue
  if (check) {
    console.error(`Out of date: ${path}`)
    stale = true
  } else {
    writeFileSync(file, content)
    console.log(`Wrote ${path}`)
  }
}
if (stale) {
  console.error('Run `node tokens/generate.mjs` and commit the result.')
  process.exit(1)
}
